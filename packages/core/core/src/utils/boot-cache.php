<?php

declare(strict_types=1);

namespace Strapi\Core\Utils;

/**
 * Not an upstream file: the production boot cache, `.strapi/cache/<name>.<key hash>.php`.
 *
 * Upstream boots once per process; under PHP-FPM every request boots. What a boot computes from
 * its inputs alone, the same way every time (the database metadata, the compiled route table), is
 * written once as a `var_export`ed array and read back with `include`, which opcache serves from
 * shared memory as an immutable array: no parsing, no copying.
 *
 * The key is in the file name, not only in the file: production opcache often runs with
 * `opcache.validate_timestamps=0`, where a file rewritten in place keeps serving its old contents
 * until a restart. A new key is a new file; writing one removes the entry's other files.
 *
 * Only plain data is written (arrays and scalars): a value holding an object or a closure is not
 * cached, and the caller computes it every time. A directory that cannot be written leaves the
 * cache empty, never an error. Strapi opens one on a settled boot only (`Strapi::bootCache()`), and
 * only where opcache keeps scripts in shared memory ({@see supported()}).
 */
final class BootCache
{
    public function __construct(public readonly string $dir)
    {
    }

    /**
     * Whether opcache serves this process's scripts from shared memory. Without it an entry is
     * parsed at every include, which takes as long as computing it (the database metadata of
     * examples/getstarted: 450 KB, about 4 ms either way), and so does opcache's file cache, which
     * unserializes the array from disk.
     */
    public static function supported(): bool
    {
        if (!function_exists('opcache_get_status') || !filter_var(ini_get('opcache.enable'), FILTER_VALIDATE_BOOL)) {
            return false;
        }
        if (in_array(PHP_SAPI, ['cli', 'phpdbg'], true) && !filter_var(ini_get('opcache.enable_cli'), FILTER_VALIDATE_BOOL)) {
            return false;
        }

        return !filter_var(ini_get('opcache.file_cache_only'), FILTER_VALIDATE_BOOL);
    }

    /**
     * The entry `$name` stored under `$key`, or null when there is none.
     *
     * @return array<array-key, mixed>|null
     */
    public function get(string $name, string $key): ?array
    {
        $file = $this->file($name, $key);
        if (!is_file($file)) {
            return null;
        }

        try {
            $data = include $file;
        } catch (\Throwable) {
            // a truncated or foreign file: rewritten by the next set()
            return null;
        }

        return is_array($data) ? $data : null;
    }

    /**
     * Store `$data` as the entry `$name` under `$key`, replacing the entry's files for other keys.
     * Returns whether it was written.
     *
     * @param array<array-key, mixed> $data
     */
    public function set(string $name, string $key, array $data): bool
    {
        if (!self::isPlainData($data)) {
            return false;
        }

        if (!is_dir($this->dir) && !@mkdir($this->dir, 0o777, true) && !is_dir($this->dir)) {
            return false;
        }

        $file = $this->file($name, $key);
        $code = "<?php\n\n// Generated by Strapi (boot cache): safe to delete.\nreturn " . var_export($data, true) . ";\n";
        $tmp = $file . '.' . getmypid() . '.tmp';
        if (@file_put_contents($tmp, $code) === false) {
            return false;
        }
        if (!@rename($tmp, $file)) {
            @unlink($tmp);

            return false;
        }

        foreach (glob($this->dir . '/' . $name . '.*.php') ?: [] as $other) {
            if ($other !== $file) {
                @unlink($other);
            }
        }

        return true;
    }

    private function file(string $name, string $key): string
    {
        return $this->dir . '/' . $name . '.' . substr(hash('sha256', $key), 0, 16) . '.php';
    }

    /** Whether `$value` is made of arrays, scalars and nulls only (what `var_export` reads back as is). */
    public static function isPlainData(mixed $value): bool
    {
        if (is_array($value)) {
            foreach ($value as $item) {
                if (!self::isPlainData($item)) {
                    return false;
                }
            }

            return true;
        }

        // NAN and INF export as constants that read back, but no cached value needs them
        return $value === null || is_string($value) || is_int($value) || is_bool($value) || (is_float($value) && is_finite($value));
    }
}
