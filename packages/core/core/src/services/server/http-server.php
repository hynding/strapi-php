<?php

declare(strict_types=1);

namespace Strapi\Core\Services\Server;

use Strapi\Core\Configuration\Configuration;
use Strapi\Core\Strapi;
use Strapi\Core\Utils\Requirements;
use Strapi\Core\Utils\Sapi;
use Strapi\Types\Core\StrapiDirectories;
use Symfony\Component\Process\Process;

/**
 * Port of packages/core/core/src/services/server/http-server.ts.
 *
 * Node's `http.createServer` becomes PHP's built-in web server (`php -S host:port -t public <router>`)
 * run through symfony/process: it is the simplest option that needs no extension and matches how
 * a project is deployed (FPM/FrankenPHP execute `public/index.php` per request; the built-in server
 * does the same). The router script is the project's `public/index.php` when it exists, otherwise a
 * generated `.tmp/strapi-router.php` that boots Strapi and calls `server.handle()`.
 *
 * Because the built-in server runs requests in a child process, the Strapi instance that called
 * `listen()` only logs the startup message; each request boots its own instance (schema sync is a
 * hash check after the first boot). For a persistent process use FrankenPHP worker mode with the
 * same `public/index.php`.
 */
final class HttpServer
{
    private ?Process $process = null;

    public function __construct(private readonly Strapi $strapi, public readonly Server $server)
    {
    }

    public static function createHTTPServer(Strapi $strapi, Server $server): self
    {
        return new self($strapi, $server);
    }

    public function listening(): bool
    {
        return $this->process !== null && $this->process->isRunning();
    }

    /**
     * The built-in server's command line. PHP's own multipart parser keeps only the last of a
     * repeated field, so several `files` in one upload would arrive as one; koa-body keeps them
     * all. With `enable_post_data_reading` off, strapi::body (middlewares/body.php) parses the raw
     * body itself, repeated fields included, as it does under FrankenPHP and in tests/api.
     *
     * @return list<string>
     */
    public static function command(string $php, string $host, int $port, string $public, string $router): array
    {
        return [$php, '-d', 'enable_post_data_reading=0', '-S', "{$host}:{$port}", '-t', $public, $router];
    }

    /** @param callable(): void|null $onListen */
    public function listen(string $host, int $port, ?callable $onListen = null): void
    {
        $root = $this->strapi->dirs()->root;
        $public = $this->strapi->dirs()->public;
        $router = $public . '/index.php';

        if (!is_file($router)) {
            $router = $this->writeRouterScript($root);
        }

        if (self::portInUse($host, $port)) {
            $this->strapi->stopWithError(new \RuntimeException("The port {$port} is already used by another application."));
        }

        $this->process = new Process(self::command(PHP_BINARY, $host, $port, $public, $router), $root, [
            ...array_filter(getenv(), 'is_string'),
            'STRAPI_APP_DIR' => $root,
            'PHP_CLI_SERVER_WORKERS' => (string) ((int) ($this->strapi->config()->get('server.http.workers', 4))),
        ], null, null);

        $this->process->start(function (string $type, string $buffer): void {
            fwrite($type === Process::ERR ? STDERR : STDOUT, $buffer);
        });

        // wait for the socket
        $deadline = microtime(true) + 5;
        while (microtime(true) < $deadline && !self::portInUse($host === '0.0.0.0' ? '127.0.0.1' : $host, $port)) {
            usleep(50_000);
            if (!$this->process->isRunning()) {
                $this->strapi->stopWithError(new \RuntimeException('The built-in server stopped unexpectedly: ' . $this->process->getErrorOutput()));
            }
        }

        if ($onListen !== null) {
            $onListen();
        }

        $this->process->wait();
    }

    public static function portInUse(string $host, int $port): bool
    {
        $socket = @stream_socket_client("tcp://{$host}:{$port}", $errno, $errstr, 0.2);
        if ($socket === false) {
            return false;
        }
        fclose($socket);

        return true;
    }

    private function writeRouterScript(string $root): string
    {
        $dir = $root . '/.tmp';
        if (!is_dir($dir)) {
            mkdir($dir, 0o777, true);
        }
        $file = $dir . '/strapi-router.php';
        $autoload = self::findAutoload($root);

        $script = <<<PHP
<?php
// generated by strapi/core HttpServer: boots Strapi and handles the request (built-in server mode)
declare(strict_types=1);
require {$autoload};
\$public = {$this->export($this->strapi->dirs()->public)};
\$path = parse_url(\$_SERVER['REQUEST_URI'] ?? '/', PHP_URL_PATH) ?? '/';
if (\$path !== '/' && is_file(\$public . \$path)) {
    return false; // serve the static file
}
\$strapi = \\Strapi\\Core\\Core::createStrapi(['appDir' => {$this->export($root)}])->load();
\\Strapi\\Core\\Services\\Server\\HttpServer::emit(\$strapi->server()->handle(\\Strapi\\Core\\Services\\Server\\HttpServer::requestFromGlobals()));
PHP;
        file_put_contents($file, $script);

        return $file;
    }

    private function export(string $value): string
    {
        return var_export($value, true);
    }

    private static function findAutoload(string $root): string
    {
        foreach ([$root . '/vendor/autoload.php', dirname(__DIR__, 5) . '/vendor/autoload.php', dirname(__DIR__, 7) . '/vendor/autoload.php'] as $candidate) {
            if (is_file($candidate)) {
                return var_export($candidate, true);
            }
        }

        return var_export($root . '/vendor/autoload.php', true);
    }

    /** Build the PSR-7 request from PHP globals (nyholm/psr7-server). */
    public static function requestFromGlobals(): \Psr\Http\Message\ServerRequestInterface
    {
        $factory = new \Nyholm\Psr7\Factory\Psr17Factory();
        $creator = new \Nyholm\Psr7Server\ServerRequestCreator($factory, $factory, $factory, $factory);

        $request = $creator->fromGlobals();
        $authorization = self::authorizationFromServer($_SERVER);
        if (!$request->hasHeader('Authorization') && $authorization !== null) {
            $request = $request->withHeader('Authorization', $authorization);
        }

        return $request;
    }

    /**
     * PHP port: Apache does not hand the Authorization header to PHP-FPM, FastCGI or CGI. The
     * rewrite in public/.htaccess passes it as an environment variable, which Apache renames
     * REDIRECT_HTTP_AUTHORIZATION after the rewrite to index.php, and `getallheaders()` (what the
     * request is built from) skips; Apache's own basic auth leaves PHP_AUTH_*. Without it, every
     * admin and API token is missing.
     *
     * @param array<string, mixed> $server
     */
    public static function authorizationFromServer(array $server): ?string
    {
        foreach (['HTTP_AUTHORIZATION', 'REDIRECT_HTTP_AUTHORIZATION'] as $key) {
            if (is_string($server[$key] ?? null) && $server[$key] !== '') {
                return $server[$key];
            }
        }
        if (is_string($server['PHP_AUTH_USER'] ?? null)) {
            $password = is_string($server['PHP_AUTH_PW'] ?? null) ? $server['PHP_AUTH_PW'] : '';

            return 'Basic ' . base64_encode("{$server['PHP_AUTH_USER']}:{$password}");
        }
        // PHP strips the scheme: `Digest username="ada", ...` arrives as `username="ada", ...`
        if (is_string($server['PHP_AUTH_DIGEST'] ?? null) && $server['PHP_AUTH_DIGEST'] !== '') {
            return 'Digest ' . $server['PHP_AUTH_DIGEST'];
        }

        return null;
    }

    /**
     * PHP port: the front controller's answer to a boot that throws. Under a web server whose
     * requests each boot (PHP-FPM, CGI, mod_php, LiteSpeed, FrankenPHP's classic mode) an uncaught
     * error is a bare 500, or a stack trace in the page where the host leaves `display_errors` on.
     * This logs the error, with what {@see Requirements} finds wrong with the host, to PHP's error
     * log (the one log a shared host shows) and answers 500 with Strapi's error body; with
     * `NODE_ENV=development` set, the body carries the error and the findings. Elsewhere (CLI,
     * FrankenPHP worker mode, the built-in server's console) it rethrows.
     */
    public static function bootFailed(\Throwable $error, string $root, ?Strapi $strapi = null, ?string $sapi = null): void
    {
        $sapi ??= PHP_SAPI;
        if (!Sapi::isPerRequest($sapi) || $sapi === 'cli-server') {
            throw $error;
        }

        error_log("[strapi] The application failed to start: {$error}");

        // what the host lacks may be what failed (a partial vendor/): the error is logged already
        try {
            // the instance, when creating it succeeded, knows the configured client and directories
            $client = $strapi?->config()->get('database.connection.client') ?? ($_ENV['DATABASE_CLIENT'] ?? getenv('DATABASE_CLIENT'));
            $dirs = $strapi?->dirs() ?? StrapiDirectories::fromRoot($root);
            $findings = Requirements::check($dirs, is_string($client) && $client !== '' ? $client : null, ['sapi' => $sapi]);
        } catch (\Throwable $checkError) {
            $findings = [];
            error_log('[strapi] The requirements could not be checked: ' . $checkError->getMessage());
        }
        if ($findings !== []) {
            error_log("[strapi] Requirements (php bin/strapi requirements:check):\n" . Requirements::format($findings));
        }

        // only where development is explicit: a boot can fail before `.env` is read (a typo in it),
        // leaving a production host's NODE_ENV unknown, and a host that sets none runs in a
        // development it never asked for
        $nodeEnv = $_ENV['NODE_ENV'] ?? getenv('NODE_ENV');
        $details = $nodeEnv !== 'development' || Configuration::nodeEnvDefaulted() ? new \stdClass() : [
            'error' => $error->getMessage(),
            'requirements' => $findings,
        ];

        self::emit(new \Nyholm\Psr7\Response(500, ['Content-Type' => 'application/json; charset=utf-8'], (string) json_encode([
            'data' => null,
            'error' => ['status' => 500, 'name' => 'InternalServerError', 'message' => 'Internal Server Error', 'details' => $details],
        ], JSON_UNESCAPED_SLASHES | JSON_INVALID_UTF8_SUBSTITUTE)));
    }

    /** Send a PSR-7 response with PHP's SAPI. */
    public static function emit(\Psr\Http\Message\ResponseInterface $response): void
    {
        if (!headers_sent()) {
            http_response_code($response->getStatusCode());
            // the response's Content-Type is final: PHP must not append `;charset=` (default_charset)
            // to `text/*` types as Koa never does (`text/event-stream` stays as set)
            $defaultCharset = ini_get('default_charset');
            ini_set('default_charset', '');
            try {
                foreach ($response->getHeaders() as $name => $values) {
                    $first = true;
                    foreach ($values as $value) {
                        header("{$name}: {$value}", $first);
                        $first = false;
                    }
                }
            } finally {
                ini_set('default_charset', $defaultCharset === false ? 'UTF-8' : $defaultCharset);
            }
        }

        $body = $response->getBody();
        if ($body->isSeekable()) {
            $body->rewind();
        }
        while (!$body->eof()) {
            echo $body->read(65536);
        }
    }

    public function destroy(): void
    {
        if ($this->process !== null && $this->process->isRunning()) {
            $this->process->stop(2);
        }
        $this->process = null;
    }
}
