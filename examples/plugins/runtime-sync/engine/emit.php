<?php

declare(strict_types=1);

namespace StrapiPlugin\RuntimeSync\Engine;

/**
 * Mirrors engine/emit.js: writes source files for either runtime from the IR (config files),
 * from a core-factory one-liner, or as a stub carrying the original for a hand port. Output is
 * byte-identical between the two engines (the golden files under spec/fixtures prove it).
 */
final class Emit
{
    public const NOTICE = 'Generated by strapi-runtime-sync from %s. The %s runtime reads that file, %s reads this one: keep them in step (`strapi-runtime-sync status` lists the pairs).';

    /**
     * @param array{source: string, form: string, value: mixed, warnings: list<string>} $doc
     * @param 'php'|'js'|'ts' $lang
     * @return array{content: string, review: bool}
     */
    public static function config(array $doc, string $lang, string $targetRelPath): array
    {
        $todos = Ir::countTodos($doc['value']);
        $review = $todos > 0 || $doc['warnings'] !== [];
        $notes = [];
        if ($todos > 0) {
            $notes[] = "TODO(runtime-sync): {$todos} expression(s) could not be translated; search for TODO(runtime-sync).";
        }
        foreach ($doc['warnings'] as $warning) {
            $notes[] = "Note: {$warning}";
        }

        $content = $lang === 'php'
            ? self::phpConfig($doc, $targetRelPath, $notes)
            : self::jsConfig($doc, $lang, $targetRelPath, $notes);

        return ['content' => $content, 'review' => $review];
    }

    /**
     * @param array{source: string, form: string, value: mixed, warnings: list<string>} $doc
     * @param list<string> $notes
     */
    private static function phpConfig(array $doc, string $target, array $notes): string
    {
        $usesEnv = $doc['form'] === 'function' || Ir::usesEnv($doc['value']);
        $ctx = ['lang' => 'php', 'depth' => Files::depth($target)];

        $out = "<?php\n\ndeclare(strict_types=1);\n\n";
        $out .= self::docBlock([sprintf(self::NOTICE, $doc['source'], 'Node', 'strapi-php'), ...$notes]) . "\n";
        if ($usesEnv) {
            $out .= "use Strapi\\Utils\\EnvHelper;\n\n";
            $out .= 'return static fn (EnvHelper $env): array => ' . self::phpValue($doc['value'], 0, $ctx) . ";\n";
        } else {
            $out .= 'return ' . self::phpValue($doc['value'], 0, $ctx) . ";\n";
        }

        return $out;
    }

    /**
     * @param array{source: string, form: string, value: mixed, warnings: list<string>} $doc
     * @param 'js'|'ts' $lang
     * @param list<string> $notes
     */
    private static function jsConfig(array $doc, string $lang, string $target, array $notes): string
    {
        $usesEnv = $doc['form'] === 'function' || Ir::usesEnv($doc['value']);
        $ctx = ['lang' => $lang, 'depth' => Files::depth($target)];
        $body = self::jsValue($doc['value'], 0, $ctx);
        if ($usesEnv && $body !== '' && $body[0] === '{') {
            $body = "({$body})";
        }

        $out = self::docBlock([sprintf(self::NOTICE, $doc['source'], 'strapi-php', 'Node'), ...$notes]) . "\n";
        $imports = [];
        if (Ir::usesRoot($doc['value'])) {
            $imports[] = $lang === 'ts' ? "import path from 'path';" : "const path = require('path');";
        }
        if ($lang === 'ts' && $usesEnv) {
            $imports[] = "import type { Core } from '@strapi/strapi';";
        }
        if ($imports !== []) {
            $out .= implode("\n", $imports) . "\n\n";
        }
        if ($lang === 'ts') {
            $out .= $usesEnv ? "export default ({ env }: Core.Config.Shared.ConfigParams) => {$body};\n" : "export default {$body};\n";
        } else {
            $out .= $usesEnv ? "module.exports = ({ env }) => {$body};\n" : "module.exports = {$body};\n";
        }

        return $out;
    }

    /** @param list<string> $lines */
    public static function docBlock(array $lines): string
    {
        $out = "/**\n";
        foreach ($lines as $i => $line) {
            if ($i > 0) {
                $out .= " *\n";
            }
            foreach (self::wrap($line, 96) as $part) {
                $out .= " * {$part}\n";
            }
        }

        return $out . " */\n";
    }

    /** @return list<string> */
    private static function wrap(string $text, int $width): array
    {
        $lines = [];
        $current = '';
        foreach (explode(' ', $text) as $word) {
            if ($current !== '' && strlen($current) + 1 + strlen($word) > $width) {
                $lines[] = $current;
                $current = $word;
            } else {
                $current = $current === '' ? $word : "{$current} {$word}";
            }
        }
        if ($current !== '') {
            $lines[] = $current;
        }

        return $lines;
    }

    // --- values ---------------------------------------------------------------------------------

    /** @param array{lang: string, depth: int} $ctx */
    public static function phpValue(mixed $value, int $indent, array $ctx): string
    {
        $pad = str_repeat('    ', $indent);
        $inner = str_repeat('    ', $indent + 1);

        if (Ir::isEnv($value)) {
            return self::phpEnv($value, $indent, $ctx);
        }
        if (Ir::isConcat($value)) {
            return implode(' . ', array_map(fn (mixed $part): string => self::phpValue($part, $indent, $ctx), $value->{'$concat'}));
        }
        if (Ir::isRoot($value)) {
            return $ctx['depth'] <= 1 ? 'dirname(__DIR__)' : "dirname(__DIR__, {$ctx['depth']})";
        }
        if (Ir::isTodo($value)) {
            return 'null /* TODO(runtime-sync): port from ' . $value->lang . ': ' . str_replace('*/', '* /', $value->{'$todo'}) . ' */';
        }
        if ($value instanceof \stdClass) {
            $vars = get_object_vars($value);
            if ($vars === []) {
                return '[]';
            }
            $out = "[\n";
            foreach ($vars as $key => $child) {
                $out .= $inner . self::phpString((string) $key) . ' => ' . self::phpValue($child, $indent + 1, $ctx) . ",\n";
            }

            return $out . $pad . ']';
        }
        if (is_array($value)) {
            if ($value === []) {
                return '[]';
            }
            $out = "[\n";
            foreach ($value as $child) {
                $out .= $inner . self::phpValue($child, $indent + 1, $ctx) . ",\n";
            }

            return $out . $pad . ']';
        }

        return self::phpScalar($value);
    }

    /** @param array{lang: string, depth: int} $ctx */
    private static function phpEnv(\stdClass $ref, int $indent, array $ctx): string
    {
        $type = $ref->{'$env'};
        $args = [self::phpString((string) $ref->key)];
        if ($type === 'oneOf') {
            $args[] = self::phpValue(array_values((array) ($ref->expected ?? [])), $indent, $ctx);
        }
        if (property_exists($ref, 'default')) {
            $args[] = self::phpValue($ref->default, $indent, $ctx);
        }
        $call = $type === 'string' ? '$env(' : '$env->' . $type . '(';

        return $call . implode(', ', $args) . ')';
    }

    public static function phpString(string $value): string
    {
        if (preg_match('/[\x00-\x1f]/', $value) === 1) {
            return '"' . str_replace(['\\', '"', '$', "\n", "\r", "\t"], ['\\\\', '\\"', '\\$', '\\n', '\\r', '\\t'], $value) . '"';
        }

        return "'" . str_replace(['\\', "'"], ['\\\\', "\\'"], $value) . "'";
    }

    public static function phpScalar(mixed $value): string
    {
        return match (true) {
            is_string($value) => self::phpString($value),
            is_bool($value) => $value ? 'true' : 'false',
            $value === null => 'null',
            is_int($value) => (string) $value,
            is_float($value) => self::floatLiteral($value),
            default => throw new \InvalidArgumentException('Cannot emit ' . get_debug_type($value)),
        };
    }

    /** @param array{lang: string, depth: int} $ctx */
    public static function jsValue(mixed $value, int $indent, array $ctx): string
    {
        $pad = str_repeat('  ', $indent);
        $inner = str_repeat('  ', $indent + 1);

        if (Ir::isEnv($value)) {
            return self::jsEnv($value, $indent, $ctx);
        }
        if (Ir::isConcat($value)) {
            return self::jsConcat($value->{'$concat'}, $indent, $ctx);
        }
        if (Ir::isRoot($value)) {
            return self::jsRoot($ctx, []);
        }
        if (Ir::isTodo($value)) {
            return 'undefined /* TODO(runtime-sync): port from ' . $value->lang . ': ' . str_replace('*/', '* /', $value->{'$todo'}) . ' */';
        }
        if ($value instanceof \stdClass) {
            $vars = get_object_vars($value);
            if ($vars === []) {
                return '{}';
            }
            $out = "{\n";
            foreach ($vars as $key => $child) {
                $out .= $inner . self::jsKey((string) $key) . ': ' . self::jsValue($child, $indent + 1, $ctx) . ",\n";
            }

            return $out . $pad . '}';
        }
        if (is_array($value)) {
            if ($value === []) {
                return '[]';
            }
            $out = "[\n";
            foreach ($value as $child) {
                $out .= $inner . self::jsValue($child, $indent + 1, $ctx) . ",\n";
            }

            return $out . $pad . ']';
        }

        return self::jsScalar($value);
    }

    /** @param array{lang: string, depth: int} $ctx */
    private static function jsEnv(\stdClass $ref, int $indent, array $ctx): string
    {
        $type = $ref->{'$env'};
        $args = [self::jsString((string) $ref->key)];
        if ($type === 'oneOf') {
            $args[] = self::jsValue(array_values((array) ($ref->expected ?? [])), $indent, $ctx);
        }
        if (property_exists($ref, 'default')) {
            $args[] = self::jsValue($ref->default, $indent, $ctx);
        }
        $call = $type === 'string' ? 'env(' : "env.{$type}(";

        return $call . implode(', ', $args) . ')';
    }

    /**
     * `path.join(__dirname, '..', ...)`: the project root from a file `depth` directories deep.
     *
     * @param array{lang: string, depth: int} $ctx
     * @param list<string> $extra already-emitted arguments appended to the join
     */
    private static function jsRoot(array $ctx, array $extra): string
    {
        $args = ['__dirname', ...array_fill(0, max(1, $ctx['depth']), "'..'"), ...$extra];

        return 'path.join(' . implode(', ', $args) . ')';
    }

    /**
     * @param list<mixed> $parts
     * @param array{lang: string, depth: int} $ctx
     */
    private static function jsConcat(array $parts, int $indent, array $ctx): string
    {
        // [$root, '/sub/', env(...)] → path.join(__dirname, '..', 'sub', env(...))
        if (count($parts) >= 2 && Ir::isRoot($parts[0]) && is_string($parts[1]) && str_starts_with($parts[1], '/')) {
            $literal = trim($parts[1], '/');
            $extra = $literal === '' ? [] : [self::jsString($literal)];
            $rest = array_slice($parts, 2);
            if ($rest === [] || (count($rest) === 1 && Ir::isEnv($rest[0]) && str_ends_with($parts[1], '/'))) {
                foreach ($rest as $part) {
                    $extra[] = self::jsValue($part, $indent, $ctx);
                }

                return self::jsRoot($ctx, $extra);
            }
        }

        return implode(' + ', array_map(fn (mixed $part): string => self::jsValue($part, $indent, $ctx), $parts));
    }

    public static function jsKey(string $key): string
    {
        return preg_match('/^[A-Za-z_$][\w$]*$/', $key) === 1 ? $key : self::jsString($key);
    }

    public static function jsString(string $value): string
    {
        return "'" . str_replace(['\\', "'", "\n", "\r", "\t"], ['\\\\', "\\'", '\\n', '\\r', '\\t'], $value) . "'";
    }

    public static function jsScalar(mixed $value): string
    {
        return match (true) {
            is_string($value) => self::jsString($value),
            is_bool($value) => $value ? 'true' : 'false',
            $value === null => 'null',
            is_int($value) => (string) $value,
            is_float($value) => self::floatLiteral($value),
            default => throw new \InvalidArgumentException('Cannot emit ' . get_debug_type($value)),
        };
    }

    /** `1.0` stays a float literal in PHP; JS prints integral floats as integers, like JSON. */
    private static function floatLiteral(float $value): string
    {
        $text = (string) json_encode($value, JSON_PRESERVE_ZERO_FRACTION);

        return $text;
    }

    // --- core factories ---------------------------------------------------------------------------

    /**
     * The one-liner `strapi generate` writes.
     *
     * @param 'php'|'js'|'ts' $lang
     */
    public static function coreFactory(string $factory, string $uid, string $lang): string
    {
        $kind = Source::FACTORIES[$factory] ?? 'module';
        $title = Source::describe($kind, $uid);
        $uidLiteral = $lang === 'php' ? self::phpString($uid) : self::jsString($uid);

        return match ($lang) {
            'php' => "<?php\n\ndeclare(strict_types=1);\n\n/**\n * {$title}\n */\n\nuse Strapi\\Core\\Factories;\n\nreturn Factories::{$factory}({$uidLiteral});\n",
            'ts' => "/**\n * {$title}\n */\n\nimport { factories } from '@strapi/strapi';\n\nexport default factories.{$factory}({$uidLiteral});\n",
            default => "'use strict';\n\n/**\n * {$title}\n */\n\nconst { {$factory} } = require('@strapi/strapi').factories;\n\nmodule.exports = {$factory}({$uidLiteral});\n",
        };
    }

    // --- stubs ----------------------------------------------------------------------------------

    /**
     * A file of the right shape for the other runtime, with the original attached as a comment
     * for the hand port. Policies deny and migrations throw until ported; the rest pass through.
     *
     * @param string $shape lifecycles, policy, middleware, extension, migration, controller, service, router; anything else is a plain module
     * @param 'php'|'js'|'ts' $lang
     */
    public static function stub(string $shape, string $lang, string $sourceRelPath, string $sourceCode, ?string $uid = null): string
    {
        $todo = "TODO(runtime-sync): port {$sourceRelPath} by hand, then remove this notice.";
        $original = "/* Original ({$sourceRelPath}):\n" . str_replace('*/', '* /', rtrim($sourceCode)) . "\n*/\n";

        if ($lang === 'php') {
            $body = self::phpStubBody($shape, $todo, $uid);

            return "<?php\n\ndeclare(strict_types=1);\n\n" . $body['uses'] . self::docBlock(["Stub generated by strapi-runtime-sync from {$sourceRelPath}.", $todo]) . $body['code'] . "\n" . $original;
        }

        $body = self::jsStubBody($shape, $lang, $todo, $uid);

        return self::docBlock(["Stub generated by strapi-runtime-sync from {$sourceRelPath}.", $todo]) . $body['imports'] . $body['code'] . "\n" . $original;
    }

    /** @return array{uses: string, code: string} */
    private static function phpStubBody(string $shape, string $todo, ?string $uid): array
    {
        $uidLiteral = self::phpString((string) $uid);
        $factory = array_search($shape, Source::FACTORIES, true);

        return match ($shape) {
            'lifecycles' => [
                'uses' => "use Strapi\\Database\\Lifecycles\\Event;\n\n",
                'code' => "return [\n    // 'beforeCreate' => static function (Event \$event): void {\n    // },\n];\n",
            ],
            'policy' => [
                'uses' => "use Strapi\\Core\\Strapi;\nuse Strapi\\Utils\\Policy\\PolicyContext;\n\n",
                'code' => "return static function (PolicyContext \$policyCtx, array \$config, Strapi \$strapi): bool {\n    // {$todo}\n    return false;\n};\n",
            ],
            'middleware' => [
                'uses' => "use Strapi\\Core\\Strapi;\nuse Strapi\\Types\\Core\\Context;\n\n",
                'code' => "return static function (array \$config, Strapi \$strapi): callable {\n    return static function (Context \$ctx, callable \$next): void {\n        // {$todo}\n        \$next();\n    };\n};\n",
            ],
            'extension' => [
                'uses' => "use Strapi\\Core\\Strapi;\n\n",
                'code' => "return static function (array \$plugin, Strapi \$strapi): array {\n    // {$todo}\n    return \$plugin;\n};\n",
            ],
            'migration' => [
                'uses' => "use Doctrine\\DBAL\\Connection;\nuse Strapi\\Database\\Database;\n\n",
                'code' => "return [\n    'up' => static function (Connection \$trx, Database \$db): void {\n        throw new \\LogicException('{$todo}');\n    },\n    'down' => static function (Connection \$trx, Database \$db): void {\n        throw new \\LogicException('{$todo}');\n    },\n];\n",
            ],
            'controller', 'service' => [
                'uses' => "use Strapi\\Core\\Factories;\nuse Strapi\\Core\\Strapi;\n\n",
                'code' => "return Factories::{$factory}({$uidLiteral}, static fn (Strapi \$strapi): array => [\n    // {$todo}\n]);\n",
            ],
            'router' => [
                'uses' => "use Strapi\\Core\\Factories;\n\n",
                'code' => "return Factories::createCoreRouter({$uidLiteral}, [\n    // {$todo}\n]);\n",
            ],
            default => [
                'uses' => '',
                'code' => "return [\n    // {$todo}\n];\n",
            ],
        };
    }

    /** @return array{imports: string, code: string} */
    private static function jsStubBody(string $shape, string $lang, string $todo, ?string $uid): array
    {
        $uidLiteral = self::jsString((string) $uid);
        $factory = array_search($shape, Source::FACTORIES, true);
        $export = $lang === 'ts' ? 'export default' : 'module.exports =';

        return match ($shape) {
            'lifecycles' => ['imports' => '', 'code' => "{$export} {\n  // beforeCreate(event) {},\n};\n"],
            'policy' => ['imports' => '', 'code' => "{$export} (policyContext, config, { strapi }) => {\n  // {$todo}\n  return false;\n};\n"],
            'middleware' => ['imports' => '', 'code' => "{$export} (config, { strapi }) => async (ctx, next) => {\n  // {$todo}\n  await next();\n};\n"],
            'extension' => ['imports' => '', 'code' => "{$export} (plugin) => {\n  // {$todo}\n  return plugin;\n};\n"],
            'migration' => ['imports' => '', 'code' => "{$export} {\n  async up(knex) {\n    throw new Error('{$todo}');\n  },\n  async down(knex) {\n    throw new Error('{$todo}');\n  },\n};\n"],
            'controller', 'service', 'router' => [
                'imports' => $lang === 'ts' ? "import { factories } from '@strapi/strapi';\n\n" : "const { {$factory} } = require('@strapi/strapi').factories;\n\n",
                'code' => ($lang === 'ts' ? "export default factories.{$factory}(" : "module.exports = {$factory}(") . $uidLiteral . ($shape === 'router' ? ", {\n  // {$todo}\n});\n" : ", ({ strapi }) => ({\n  // {$todo}\n}));\n"),
            ],
            default => ['imports' => '', 'code' => "{$export} {\n  // {$todo}\n};\n"],
        };
    }
}
