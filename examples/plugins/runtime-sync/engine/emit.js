'use strict';

/**
 * Mirrors engine/emit.php: writes source files for either runtime from the IR (config files),
 * from a core-factory one-liner, or as a stub carrying the original for a hand port. Output is
 * byte-identical between the two engines (the golden files under tests/fixtures prove it).
 */
const files = require('./files');
const ir = require('./ir');
const source = require('./source');

const NOTICE = (from, reader, self) => `Generated by strapi-runtime-sync from ${from}. The ${reader} runtime reads that file, ${self} reads this one: keep them in step (\`strapi-runtime-sync status\` lists the pairs).`;

function config(doc, lang, targetRelPath) {
  const todos = ir.countTodos(doc.value);
  const review = todos > 0 || doc.warnings.length > 0;
  const notes = [];
  if (todos > 0) notes.push(`TODO(runtime-sync): ${todos} expression(s) could not be translated; search for TODO(runtime-sync).`);
  for (const warning of doc.warnings) notes.push(`Note: ${warning}`);
  const content = lang === 'php' ? phpConfig(doc, targetRelPath, notes) : jsConfig(doc, lang, targetRelPath, notes);
  return { content, review };
}

function phpConfig(doc, target, notes) {
  const usesEnv = doc.form === 'function' || ir.usesEnv(doc.value);
  const ctx = { lang: 'php', depth: files.depth(target) };
  let out = '<?php\n\ndeclare(strict_types=1);\n\n';
  out += `${docBlock([NOTICE(doc.source, 'Node', 'strapi-php'), ...notes])}\n`;
  if (usesEnv) {
    out += 'use Strapi\\Utils\\EnvHelper;\n\n';
    out += `return static fn (EnvHelper $env): array => ${phpValue(doc.value, 0, ctx)};\n`;
  } else {
    out += `return ${phpValue(doc.value, 0, ctx)};\n`;
  }
  return out;
}

function jsConfig(doc, lang, target, notes) {
  const usesEnv = doc.form === 'function' || ir.usesEnv(doc.value);
  const ctx = { lang, depth: files.depth(target) };
  let body = jsValue(doc.value, 0, ctx);
  if (usesEnv && body !== '' && body[0] === '{') body = `(${body})`;

  let out = `${docBlock([NOTICE(doc.source, 'strapi-php', 'Node'), ...notes])}\n`;
  const imports = [];
  if (ir.usesRoot(doc.value)) imports.push(lang === 'ts' ? "import path from 'path';" : "const path = require('path');");
  if (lang === 'ts' && usesEnv) imports.push("import type { Core } from '@strapi/strapi';");
  if (imports.length > 0) out += `${imports.join('\n')}\n\n`;
  if (lang === 'ts') out += usesEnv ? `export default ({ env }: Core.Config.Shared.ConfigParams) => ${body};\n` : `export default ${body};\n`;
  else out += usesEnv ? `module.exports = ({ env }) => ${body};\n` : `module.exports = ${body};\n`;
  return out;
}

function docBlock(lines) {
  let out = '/**\n';
  lines.forEach((line, i) => {
    if (i > 0) out += ' *\n';
    for (const part of wrap(line, 96)) out += ` * ${part}\n`;
  });
  return `${out} */\n`;
}

function wrap(text, width) {
  const lines = [];
  let current = '';
  for (const word of text.split(' ')) {
    if (current !== '' && current.length + 1 + word.length > width) {
      lines.push(current);
      current = word;
    } else {
      current = current === '' ? word : `${current} ${word}`;
    }
  }
  if (current !== '') lines.push(current);
  return lines;
}

// --- values -----------------------------------------------------------------------------------

function phpValue(value, indent, ctx) {
  const pad = '    '.repeat(indent);
  const inner = '    '.repeat(indent + 1);
  if (ir.isEnv(value)) return phpEnv(value, indent, ctx);
  if (ir.isConcat(value)) return value.$concat.map((part) => phpValue(part, indent, ctx)).join(' . ');
  if (ir.isRoot(value)) return ctx.depth <= 1 ? 'dirname(__DIR__)' : `dirname(__DIR__, ${ctx.depth})`;
  if (ir.isTodo(value)) return `null /* TODO(runtime-sync): port from ${value.lang}: ${value.$todo.replace(/\*\//g, '* /')} */`;
  if (ir.isObject(value)) {
    const entries = Object.entries(value);
    if (entries.length === 0) return '[]';
    let out = '[\n';
    for (const [key, child] of entries) out += `${inner}${phpString(key)} => ${phpValue(child, indent + 1, ctx)},\n`;
    return `${out}${pad}]`;
  }
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    let out = '[\n';
    for (const child of value) out += `${inner}${phpValue(child, indent + 1, ctx)},\n`;
    return `${out}${pad}]`;
  }
  return phpScalar(value);
}

function phpEnv(ref, indent, ctx) {
  const type = ref.$env;
  const args = [phpString(String(ref.key))];
  if (type === 'oneOf') args.push(phpValue(ref.expected ?? [], indent, ctx));
  if ('default' in ref) args.push(phpValue(ref.default, indent, ctx));
  const call = type === 'string' ? '$env(' : `$env->${type}(`;
  return `${call}${args.join(', ')})`;
}

function phpString(value) {
  if (/[\x00-\x1f]/.test(value)) {
    return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\$/g, '\\$').replace(/\n/g, '\\n').replace(/\r/g, '\\r').replace(/\t/g, '\\t')}"`;
  }
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
}

function phpScalar(value) {
  if (typeof value === 'string') return phpString(value);
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'number') return floatLiteral(value);
  throw new Error(`Cannot emit ${typeof value}`);
}

function jsValue(value, indent, ctx) {
  const pad = '  '.repeat(indent);
  const inner = '  '.repeat(indent + 1);
  if (ir.isEnv(value)) return jsEnv(value, indent, ctx);
  if (ir.isConcat(value)) return jsConcat(value.$concat, indent, ctx);
  if (ir.isRoot(value)) return jsRoot(ctx, []);
  if (ir.isTodo(value)) return `undefined /* TODO(runtime-sync): port from ${value.lang}: ${value.$todo.replace(/\*\//g, '* /')} */`;
  if (ir.isObject(value)) {
    const entries = Object.entries(value);
    if (entries.length === 0) return '{}';
    let out = '{\n';
    for (const [key, child] of entries) out += `${inner}${jsKey(key)}: ${jsValue(child, indent + 1, ctx)},\n`;
    return `${out}${pad}}`;
  }
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    let out = '[\n';
    for (const child of value) out += `${inner}${jsValue(child, indent + 1, ctx)},\n`;
    return `${out}${pad}]`;
  }
  return jsScalar(value);
}

function jsEnv(ref, indent, ctx) {
  const type = ref.$env;
  const args = [jsString(String(ref.key))];
  if (type === 'oneOf') args.push(jsValue(ref.expected ?? [], indent, ctx));
  if ('default' in ref) args.push(jsValue(ref.default, indent, ctx));
  const call = type === 'string' ? 'env(' : `env.${type}(`;
  return `${call}${args.join(', ')})`;
}

/** `path.join(__dirname, '..', ...)`: the project root from a file `depth` directories deep. */
function jsRoot(ctx, extra) {
  const args = ['__dirname', ...Array(Math.max(1, ctx.depth)).fill("'..'"), ...extra];
  return `path.join(${args.join(', ')})`;
}

function jsConcat(parts, indent, ctx) {
  // [$root, '/sub/', env(...)] → path.join(__dirname, '..', 'sub', env(...))
  if (parts.length >= 2 && ir.isRoot(parts[0]) && typeof parts[1] === 'string' && parts[1].startsWith('/')) {
    const literal = parts[1].replace(/^\/+|\/+$/g, '');
    const extra = literal === '' ? [] : [jsString(literal)];
    const rest = parts.slice(2);
    if (rest.length === 0 || (rest.length === 1 && ir.isEnv(rest[0]) && parts[1].endsWith('/'))) {
      for (const part of rest) extra.push(jsValue(part, indent, ctx));
      return jsRoot(ctx, extra);
    }
  }
  return parts.map((part) => jsValue(part, indent, ctx)).join(' + ');
}

const jsKey = (key) => (/^[A-Za-z_$][\w$]*$/.test(key) ? key : jsString(key));

const jsString = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n').replace(/\r/g, '\\r').replace(/\t/g, '\\t')}'`;

function jsScalar(value) {
  if (typeof value === 'string') return jsString(value);
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'number') return floatLiteral(value);
  throw new Error(`Cannot emit ${typeof value}`);
}

/** JSON's number spelling, the same in both engines. */
const floatLiteral = (value) => JSON.stringify(value);

// --- core factories -----------------------------------------------------------------------------

/** The one-liner `strapi generate` writes. */
function coreFactory(factory, uid, lang) {
  const kind = source.FACTORIES[factory] ?? 'module';
  const title = source.describe(kind, uid);
  const uidLiteral = lang === 'php' ? phpString(uid) : jsString(uid);
  if (lang === 'php') return `<?php\n\ndeclare(strict_types=1);\n\n/**\n * ${title}\n */\n\nuse Strapi\\Core\\Factories;\n\nreturn Factories::${factory}(${uidLiteral});\n`;
  if (lang === 'ts') return `/**\n * ${title}\n */\n\nimport { factories } from '@strapi/strapi';\n\nexport default factories.${factory}(${uidLiteral});\n`;
  return `'use strict';\n\n/**\n * ${title}\n */\n\nconst { ${factory} } = require('@strapi/strapi').factories;\n\nmodule.exports = ${factory}(${uidLiteral});\n`;
}

// --- stubs --------------------------------------------------------------------------------------

/** A file of the right shape for the other runtime, with the original attached as a comment for the hand port. */
function stub(shape, lang, sourceRelPath, sourceCode, uid = null) {
  const todo = `TODO(runtime-sync): port ${sourceRelPath} by hand, then remove this notice.`;
  const original = `/* Original (${sourceRelPath}):\n${sourceCode.replace(/\s+$/, '').replace(/\*\//g, '* /')}\n*/\n`;
  if (lang === 'php') {
    const body = phpStubBody(shape, todo, uid);
    return `<?php\n\ndeclare(strict_types=1);\n\n${body.uses}${docBlock([`Stub generated by strapi-runtime-sync from ${sourceRelPath}.`, todo])}${body.code}\n${original}`;
  }
  const body = jsStubBody(shape, lang, todo, uid);
  return `${docBlock([`Stub generated by strapi-runtime-sync from ${sourceRelPath}.`, todo])}${body.imports}${body.code}\n${original}`;
}

function phpStubBody(shape, todo, uid) {
  const uidLiteral = phpString(String(uid ?? ''));
  const factory = Object.keys(source.FACTORIES).find((f) => source.FACTORIES[f] === shape);
  switch (shape) {
    case 'lifecycles':
      return { uses: 'use Strapi\\Database\\Lifecycles\\Event;\n\n', code: "return [\n    // 'beforeCreate' => static function (Event $event): void {\n    // },\n];\n" };
    case 'policy':
      return { uses: 'use Strapi\\Core\\Strapi;\nuse Strapi\\Utils\\Policy\\PolicyContext;\n\n', code: `return static function (PolicyContext $policyCtx, array $config, Strapi $strapi): bool {\n    // ${todo}\n    return false;\n};\n` };
    case 'middleware':
      return { uses: 'use Strapi\\Core\\Strapi;\nuse Strapi\\Types\\Core\\Context;\n\n', code: `return static function (array $config, Strapi $strapi): callable {\n    return static function (Context $ctx, callable $next): void {\n        // ${todo}\n        $next();\n    };\n};\n` };
    case 'extension':
      return { uses: 'use Strapi\\Core\\Strapi;\n\n', code: `return static function (array $plugin, Strapi $strapi): array {\n    // ${todo}\n    return $plugin;\n};\n` };
    case 'migration':
      return { uses: 'use Doctrine\\DBAL\\Connection;\nuse Strapi\\Database\\Database;\n\n', code: `return [\n    'up' => static function (Connection $trx, Database $db): void {\n        throw new \\LogicException('${todo}');\n    },\n    'down' => static function (Connection $trx, Database $db): void {\n        throw new \\LogicException('${todo}');\n    },\n];\n` };
    case 'controller':
    case 'service':
      return { uses: 'use Strapi\\Core\\Factories;\nuse Strapi\\Core\\Strapi;\n\n', code: `return Factories::${factory}(${uidLiteral}, static fn (Strapi $strapi): array => [\n    // ${todo}\n]);\n` };
    case 'router':
      return { uses: 'use Strapi\\Core\\Factories;\n\n', code: `return Factories::createCoreRouter(${uidLiteral}, [\n    // ${todo}\n]);\n` };
    default:
      return { uses: '', code: `return [\n    // ${todo}\n];\n` };
  }
}

function jsStubBody(shape, lang, todo, uid) {
  const uidLiteral = jsString(String(uid ?? ''));
  const factory = Object.keys(source.FACTORIES).find((f) => source.FACTORIES[f] === shape);
  const exp = lang === 'ts' ? 'export default' : 'module.exports =';
  switch (shape) {
    case 'lifecycles':
      return { imports: '', code: `${exp} {\n  // beforeCreate(event) {},\n};\n` };
    case 'policy':
      return { imports: '', code: `${exp} (policyContext, config, { strapi }) => {\n  // ${todo}\n  return false;\n};\n` };
    case 'middleware':
      return { imports: '', code: `${exp} (config, { strapi }) => async (ctx, next) => {\n  // ${todo}\n  await next();\n};\n` };
    case 'extension':
      return { imports: '', code: `${exp} (plugin) => {\n  // ${todo}\n  return plugin;\n};\n` };
    case 'migration':
      return { imports: '', code: `${exp} {\n  async up(knex) {\n    throw new Error('${todo}');\n  },\n  async down(knex) {\n    throw new Error('${todo}');\n  },\n};\n` };
    case 'controller':
    case 'service':
    case 'router':
      return {
        imports: lang === 'ts' ? "import { factories } from '@strapi/strapi';\n\n" : `const { ${factory} } = require('@strapi/strapi').factories;\n\n`,
        code: `${lang === 'ts' ? `export default factories.${factory}(` : `module.exports = ${factory}(`}${uidLiteral}${shape === 'router' ? `, {\n  // ${todo}\n});\n` : `, ({ strapi }) => ({\n  // ${todo}\n}));\n`}`,
      };
    default:
      return { imports: '', code: `${exp} {\n  // ${todo}\n};\n` };
  }
}

module.exports = { NOTICE, config, docBlock, phpValue, phpString, phpScalar, jsValue, jsKey, jsString, jsScalar, coreFactory, stub };
